const fs = require("fs");
const path = require("path");

// No bundler, so there's nowhere to read a real env var at runtime - this
// generates a tiny gitignored source file from process.env instead, once,
// at dev/install time.
const outPath = path.join(__dirname, "..", "src", "multiplayer-config.js");

const PARTYKIT_HOST = process.env.PARTYKIT_HOST || "ws://127.0.0.1:1998";
// The default room, used when the page isn't opened with ?room=<id> (see
// src/multiplayer-client.js). Switching rooms is the reset button - old room
// data is simply orphaned, not deleted.
const MULTIPLAYER_ROOM_ID = process.env.MULTIPLAYER_ROOM_ID || "main-canvas";

const contents = `// Generated by scripts/generate-multiplayer-config.js from the
// PARTYKIT_HOST/MULTIPLAYER_ROOM_ID environment variables - do not edit
// directly, and don't commit this file (see .gitignore). Re-run
// \`npm install\` or \`npm run dev\` to regenerate it after changing either.
export const PARTYKIT_HOST = ${JSON.stringify(PARTYKIT_HOST)};
export const MULTIPLAYER_ROOM_ID = ${JSON.stringify(MULTIPLAYER_ROOM_ID)};
`;

fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} with PARTYKIT_HOST=${PARTYKIT_HOST}, MULTIPLAYER_ROOM_ID=${MULTIPLAYER_ROOM_ID}`);
